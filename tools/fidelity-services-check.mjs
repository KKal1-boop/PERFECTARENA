import {launch} from '../tests/cdp.mjs';
import assert from 'node:assert/strict';
const port=Number(process.env.FIDELITY_PORT||64145);
const page=await launch({port:9449});
const base=`http://127.0.0.1:${port}/?arena=C%3A%2FArenaProject%2Farena%2FARENA&`;
const enter=async(q)=>{await page.goto(base+q);await page.waitFor('window.__debug?.scene === "interior" && window.__debug.state().painted>2',{timeoutMs:60000});};
async function type(selector,text){await page.clickSelector(selector);await page.send('Input.insertText',{text});}
try{
 await enter('interior=START.MIF');
 await page.evalJs(`(()=>{const p=window.__debug.player();localStorage.setItem('perfectarena.character',JSON.stringify({...p,created:true,classId:'battlemage',gold:100000,health:10,maxHealth:100,spellPoints:10000,maxSpellPoints:10000,knownSpells:['Light Heal'],bag:[{id:'steel-longsword',qty:1},{id:'chrysamere',qty:1}],itemCondition:{'steel-longsword':60}}))})()`);
 await enter('interior=MAGE1.MIF');await page.evalJs('window.__debug.openSpellbook()');
 assert.equal(await page.evalJs('!!document.querySelector("#custom-spell-name")'),true);
 await type('#custom-spell-name','My Mend');
 await page.evalJs('document.querySelector("#custom-effect-0").value="Light Heal|0"');
 await page.clickSelector('[data-make-spell]');
 await page.waitFor('window.__debug.player().customSpells?.length===1');
 const made=await page.evalJs('window.__debug.player()');assert.equal(made.customSpells[0].name,'My Mend');
 await page.clickSelector('[data-cast="My Mend"]');
 await page.waitFor('window.__debug.player().health>10');
 console.log('PASS custom spell created, paid for and cast via panel');
 await page.evalJs('window.__debug.openSpellbook()'); // reopen if cast closed it
 if(!await page.evalJs('document.querySelector("#inventory").classList.contains("on")'))await page.evalJs('window.__debug.openSpellbook()');
 await page.evalJs('document.querySelector("#enchant-item").value="steel-longsword";document.querySelector("#enchant-spell").value="Light Heal"');
 await page.clickSelector('[data-enchant-item]');
 await page.waitFor('!!window.__debug.player().enchantments?.["steel-longsword"]');
 await page.evalJs('window.__debug.openBag()');
 await page.clickSelector('[data-bag="steel-longsword"][data-do="use"]');
 await page.waitFor('window.__debug.player().itemCharges?.["steel-longsword"]===99');
 await page.clickSelector('[data-bag="chrysamere"][data-do="equip"]');
 assert.equal(await page.evalJs('window.__debug.player().weapon'), 'claymore');
 await page.clickSelector('[data-bag="chrysamere"][data-do="use"]');
 await page.waitFor('window.__debug.player().itemCharges?.chrysamere===99');
 assert.equal(await page.evalJs('window.__debug.player().health'),100);
 console.log('PASS enchantment activation and Chrysamere equip/use');
 await enter('interior=EQUIP1.MIF');await page.evalJs('window.__debug.openBag()');
 await page.clickSelector('[data-repair-item="steel-longsword"]');
 await page.waitFor('window.__debug.player().repairs?.length===1');
 assert.equal(await page.evalJs('window.__debug.bag().some(r=>r.id==="steel-longsword")'),false);
 console.log('PASS smith takes damaged item, stores repair and deducts gold');
 await enter('interior=EQUIP1.MIF');
 assert.equal(await page.evalJs('window.__debug.player().repairs.length'),1);
 assert.equal(await page.evalJs('window.__debug.player().customSpells[0].name'),'My Mend');
 assert.equal(await page.evalJs('window.__debug.player().itemCharges.chrysamere'),99);
 console.log('PASS repairs, custom spells, enchantments and charges persist across reload');
 await page.evalJs(`(()=>{const p=window.__debug.player();localStorage.setItem('perfectarena.character',JSON.stringify({...p,cofferGold:9999,artifactDays:{},bag:[{id:'king-orgnums-coffer',qty:1}]}))})()`);
 await enter('interior=EQUIP1.MIF');await page.evalJs('window.__debug.openBag()');
 const goldBefore=await page.evalJs('window.__debug.player().gold');
 await page.clickSelector('[data-bag="king-orgnums-coffer"][data-do="use"]');
 await page.waitFor('window.__debug.player().cofferGold===10000');
 assert.equal(await page.evalJs('window.__debug.player().gold'),goldBefore+1);
 assert.equal(await page.evalJs('window.__debug.bag().some(r=>r.id==="king-orgnums-coffer")'),false);
 await enter('interior=EQUIP1.MIF');assert.equal(await page.evalJs('window.__debug.player().cofferGold'),10000);
 console.log('PASS Coffer final payout, disappearance and lifetime total survive reload');
 await page.evalJs(`(()=>{const p=window.__debug.player();localStorage.setItem('perfectarena.character',JSON.stringify({...p,classId:'mage',bag:[{id:'chrysamere',qty:1}]}))})()`);
 await enter('interior=EQUIP1.MIF');await page.evalJs('window.__debug.openBag()');
 await page.clickSelector('[data-bag="chrysamere"][data-do="use"]');
 assert.match(await page.evalJs('document.getElementById("notice").textContent'),/class cannot use Chrysamere/);
 console.log('PASS restricted artifact activation refused through actual Use button');
 const errors=page.consoleErrors();console.log('console errors',errors);assert.equal(errors.length,0);
}finally{page.closeBrowser();}
